def markdown():
    out = ["# Changelog", "", "All notable changes to Tidymint. Dates are release dates.", ""]
    for r in RELEASES:
        head = "Unreleased (next: %s)" % r["ver"] if r["status"] == "next" else "%s (%s)" % (r["ver"], r["date"])
        out.append("## " + head); out.append("")
        out += ["- " + x for x in r["en"]]; out.append("")
    return "\n".join(out)

